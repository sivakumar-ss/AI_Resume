-- ------------------------------------------------------------
-- 1. users — authentication identity (students and admins)
-- ------------------------------------------------------------
create table if not exists users (
    id            integer generated by default as identity primary key,
    email         varchar(255) not null unique,
    password_hash varchar(255) not null,
    full_name     varchar(120) not null,
    role          varchar(20)  not null default 'student',
    is_active     boolean      not null default true,
    token_version integer      not null default 0,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint ck_users_role check (role in ('student', 'admin'))
);


-- ------------------------------------------------------------
-- 2. student_profiles — academic data, 1:1 with users
-- ------------------------------------------------------------
create table if not exists student_profiles (
    id              integer generated by default as identity primary key,
    user_id         integer      not null unique references users (id) on delete cascade,
    branch          varchar(100) not null,
    semester        smallint     not null,
    cgpa            numeric(4, 2),
    graduation_year smallint,
    education_level varchar(30)  not null default 'undergraduate',
    college_name    varchar(200),
    experience_level varchar(30) not null default 'beginner',
    bio             text,
    interests       jsonb        not null default '[]'::jsonb,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    constraint ck_student_profiles_semester check (semester between 1 and 8),
    constraint ck_student_profiles_cgpa check (cgpa >= 0 and cgpa <= 10),
    constraint ck_student_profiles_education_level check (
        education_level in (
            'high_school', 'higher_secondary', 'diploma',
            'undergraduate', 'postgraduate', 'doctorate'
        )
    ),
    constraint ck_student_profiles_experience_level check (
        experience_level in ('beginner', 'intermediate', 'advanced')
    )
);


-- ------------------------------------------------------------
-- 3. skills — canonical skills catalogue (lowercase names)
-- ------------------------------------------------------------
create table if not exists skills (
    id          integer generated by default as identity primary key,
    name        varchar(100) not null unique,
    category    varchar(50),
    description text,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now()
);


-- ------------------------------------------------------------
-- 4. student_skills — profile ↔ skill junction (with proficiency)
-- ------------------------------------------------------------
create table if not exists student_skills (
    id                 integer generated by default as identity primary key,
    student_profile_id integer  not null references student_profiles (id) on delete cascade,
    skill_id           integer  not null references skills (id) on delete cascade,
    proficiency_level  smallint not null default 1,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),
    constraint uq_student_skills_profile_skill unique (student_profile_id, skill_id),
    constraint ck_student_skills_proficiency check (proficiency_level between 1 and 5)
);

create index if not exists ix_student_skills_skill_id
    on student_skills (skill_id);


-- ------------------------------------------------------------
-- 5. careers — catalogue scored by the recommendation engine
-- ------------------------------------------------------------
create table if not exists careers (
    id           integer generated by default as identity primary key,
    title        varchar(150) not null unique,
    description  text,
    industry     varchar(100),
    demand_score   numeric(4, 2) not null default 0,
    learning_path  text,
    prerequisites  text,
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    constraint ck_careers_demand_score check (demand_score >= 0 and demand_score <= 10)
);

create index if not exists ix_careers_demand_score
    on careers (demand_score);


-- ------------------------------------------------------------
-- 6. career_skills — career ↔ skill junction (with importance)
-- ------------------------------------------------------------
create table if not exists career_skills (
    id         integer generated by default as identity primary key,
    career_id  integer  not null references careers (id) on delete cascade,
    skill_id   integer  not null references skills (id) on delete cascade,
    importance smallint not null default 3,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_career_skills_career_skill unique (career_id, skill_id),
    constraint ck_career_skills_importance check (importance between 1 and 5)
);

create index if not exists ix_career_skills_skill_id
    on career_skills (skill_id);


-- ------------------------------------------------------------
-- 7. resumes — analysis results only (raw files/text are not stored)
-- ------------------------------------------------------------
create table if not exists resumes (
    id                integer generated by default as identity primary key,
    user_id           integer      not null references users (id) on delete cascade,
    original_filename varchar(255) not null,
    file_type         varchar(20)  not null,
    file_size_bytes   integer,
    extracted_skills  jsonb        not null default '[]'::jsonb,
    analysis_status   varchar(20)  not null default 'pending',
    model_version     varchar(50),
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    constraint ck_resumes_analysis_status
        check (analysis_status in ('pending', 'processed', 'failed'))
);

create index if not exists ix_resumes_user_created
    on resumes (user_id, created_at);


-- ------------------------------------------------------------
-- 8. assessments — interest / aptitude / skills questionnaire attempts
-- ------------------------------------------------------------
create table if not exists assessments (
    id              integer generated by default as identity primary key,
    user_id         integer     not null references users (id) on delete cascade,
    assessment_type varchar(50) not null,
    responses       jsonb       not null default '{}'::jsonb,
    score           numeric(5, 2),
    completed_at    timestamptz,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    constraint ck_assessments_score check (score >= 0)
);

create index if not exists ix_assessments_user_created
    on assessments (user_id, created_at);
create index if not exists ix_assessments_type
    on assessments (assessment_type);


-- ------------------------------------------------------------
-- 9. recommendations — one row per career per generation batch
-- ------------------------------------------------------------
create table if not exists recommendations (
    id             integer generated by default as identity primary key,
    user_id        integer     not null references users (id) on delete cascade,
    career_id      integer     not null references careers (id) on delete cascade,
    batch_id       varchar(36) not null,
    score          numeric(5, 4) not null,
    matched_skills jsonb       not null default '[]'::jsonb,
    missing_skills jsonb       not null default '[]'::jsonb,
    model_version  varchar(50) not null,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    constraint uq_recommendations_user_career_batch
        unique (user_id, career_id, batch_id),
    constraint ck_recommendations_score check (score >= 0 and score <= 1)
);

create index if not exists ix_recommendations_user_created
    on recommendations (user_id, created_at);
create index if not exists ix_recommendations_career_id
    on recommendations (career_id);
create index if not exists ix_recommendations_batch_id
    on recommendations (batch_id);


-- ------------------------------------------------------------
-- 10. learning_resources — resources to close skill gaps
-- ------------------------------------------------------------
create table if not exists learning_resources (
    id            integer generated by default as identity primary key,
    title         varchar(200) not null,
    url           varchar(500) unique,
    provider      varchar(100),
    resource_type varchar(20)  not null default 'course',
    difficulty    varchar(20),
    description   text,
    skill_id      integer      references skills (id) on delete set null,
    is_active     boolean      not null default true,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint ck_learning_resources_type
        check (resource_type in ('course', 'video', 'article', 'book', 'project', 'other')),
    constraint ck_learning_resources_difficulty
        check (difficulty in ('beginner', 'intermediate', 'advanced'))
);

create index if not exists ix_learning_resources_skill_id
    on learning_resources (skill_id);


-- ------------------------------------------------------------
-- 11. learning_progress — profile ↔ resource progress (unique pair)
-- ------------------------------------------------------------
create table if not exists learning_progress (
    id                  integer generated by default as identity primary key,
    student_profile_id  integer  not null references student_profiles (id) on delete cascade,
    learning_resource_id integer not null references learning_resources (id) on delete cascade,
    status              varchar(20) not null default 'not_started',
    progress_percent    smallint    not null default 0,
    started_at          timestamptz,
    completed_at        timestamptz,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),
    constraint uq_learning_progress_profile_resource
        unique (student_profile_id, learning_resource_id),
    constraint ck_learning_progress_status
        check (status in ('not_started', 'in_progress', 'completed')),
    constraint ck_learning_progress_percent
        check (progress_percent between 0 and 100)
);

create index if not exists ix_learning_progress_resource_id
    on learning_progress (learning_resource_id);


